#!/usr/bin/env python3
"""Program ROM zones read by the native routines and not covered by the assets: writes
port/extract/native_zones.txt (docs/sans-rom.md).

  tools/native_zones.py <covered.bin> <reads.txt>... > port/extract/native_zones.txt

<covered.bin>: `couverture_rom <assets> --octets <covered.bin> --sans data/natives.json` (word-by-word coverage
of the other asset files); <reads.txt>: outputs of `lectures_rom` in no-68000 mode (the default,
DDSOM_COUVERT=<covered.bin>). Uncovered read zones less than GAP bytes apart are merged; each one
is attributed to the Rust file that reads most of its words (first caller outside the generic mem.rs accesses).
"""
import collections
import sys

GAP = 0x10
GENERIC = ('mem.rs',)
# The reader labels ('vecteurs', 'inconnu', Rust file paths) end up in asset names (port/extract/src/natives.rs):
# keep them as they are unless the assets are regenerated.
# read before any measurement (Cpu::reset at load, program space): initial stack and PC
FIXED = [('p', 0x0, 0x8, 'vecteurs')]
# Original glitch: the freeze (PEFF type 12, shard, 0x4bd36) reads its delay `move.b (0x4bd98,PC,D0.w)` with the high
# byte of D0.w left by the random draw (word A5+0x1a): 256 reads of 16 bytes spread over ±32 KB around the
# table, many of them in the code (bot `longue_a`, frame 59,932). All are declared (the measurements only see
# a few of them); those falling outside the code are already in reste.json and vanish when filtered.
for _h in range(256):
    _a = 0x4bd98 + ((_h << 8) - (0x10000 if _h >= 0x80 else 0))
    FIXED.append(('p', _a & ~1, (_a + 16 + 1) & ~1, 'families/joueur/peff_e.rs'))
# Reads of bot `sorts_combattant` (frame 23,834, fighter scene played with all their spells): the sprite list builder
# reads a table entry out of bounds, in the code (0x3200) and before 0x1ef5e.
FIXED.append(('d', 0x3200, 0x320a, 'sprites.rs'))
FIXED.append(('d', 0x1ef5c, 0x1ef5e, 'sprites.rs'))
# Bot `sorts_noms_a` (frame 19,704): a player name starting with 0xfe (-2) gives `write_name` (0xce8de) index -4 of
# table 0xce9a4: the pointer read before the table leads to the glyph list 0xceaa0, in the code.
FIXED.append(('d', 0xceaa0, 0xceaa2, 'families/set_c_finale_c.rs'))
# readers that three call levels do not resolve (generic accesses): zone start -> file
READERS = {
    # palette page 3 of scenes 0x58 and 0x59: null entry, the game copies 32 palettes from address 0
    ('d', 0x0): 'palette.rs',
}


def reader(sites):
    for s in sites.split(';'):
        if s and not s.startswith(GENERIC):
            return s.rsplit(':', 1)[0]
    return 'inconnu'


def main():
    covered = open(sys.argv[1], 'rb').read()
    read = {'d': set(), 'p': set()}
    who = {}
    for f in sys.argv[2:]:
        for l in open(f):
            t = l.split()
            if len(t) == 5 and t[0] in ('d', 'p'):
                read[t[0]].update(range(int(t[1], 16), int(t[2], 16), 2))
            elif t and t[0] == 's':
                who.setdefault((t[1], int(t[2], 16)), reader(t[3] if len(t) > 3 else ''))
    print('# space start end(excluded) reader — generated by tools/native_zones.py, do not edit')
    zones = []
    for space, a, b, name in FIXED:
        read[space].update(range(a, b, 2))
        for m in range(a, b, 2):
            who[(space, m)] = name
    for space, base in (('d', 0), ('p', 0x200000)):
        words = sorted(a for a in read[space] if not covered[base + a // 2])
        for a in words:
            if zones and zones[-1][0] == space and a - zones[-1][2] <= GAP:
                zones[-1][2] = a + 2
                zones[-1][3][who.get((space, a), 'inconnu')] += 1
            else:
                zones.append([space, a, a + 2, collections.Counter([who.get((space, a), 'inconnu')])])
    for space, a, b, c in zones:
        print(f'{space} {a:06x} {b:06x} {READERS.get((space, a), c.most_common(1)[0][0])}')


main()
