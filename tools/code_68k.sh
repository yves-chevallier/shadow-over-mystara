#!/usr/bin/env bash
# Measures the 68000 code executed by the reference machine on all scenarios (same lists and durations as
# tools/validate_all.sh with DDSOM_SCENES=1 and DDSOM_COV=1) and writes port/extract/code_68k.txt: the byte ranges
# of executed instructions, the only bytes of the program region that `extract` does not store in data/reste.json
# (docs/sans-rom.md, full data coverage section).
#
#   DDSOM_ROMS=<roms> DDSOM_EEPROM=<eeprom> DDSOM_JOBS=10 tools/code_68k.sh [work directory]
#
# The work directory (default ~/.cache/ddsom/code_68k) keeps the measurement of each scenario: an interrupted
# measurement resumes. The result is the union of all the measurements in the directory.
set -euo pipefail
cd "$(dirname "$0")/.."
roms=${DDSOM_ROMS:-rom}
eeprom=${DDSOM_EEPROM:-testdata/eeprom_ddsom.bin}
jobs=${DDSOM_JOBS:-$(nproc)}
work=${1:-$HOME/.cache/ddsom/code_68k}
mkdir -p "$work"
DDSOM_ROMS=$roms cargo build --release -q --manifest-path port/Cargo.toml -p ddsom-game --example executed_code
bin=port/target/release/examples/executed_code
list() {
	local dir=$1 n=$2 s
	for s in "$dir"/*.txt; do
		[[ -e $s ]] && echo "$s $n"
	done
	return 0
}
{
	list scenarios 30000
	list scenarios/extra 12000
	list scenarios/boss 12000
	list scenarios/enemy 12000
	list scenarios/modes 12000
	list scenarios/scene 6500
	list scenarios/scene_end 9000
	list scenarios/cov "${COV_FRAMES:-30000}"
} > "$work/list"
export roms eeprom work bin
xargs -P "$jobs" -L 1 sh -c '
	key="$work/$(basename "$(dirname "$0")")_$(basename "$0" .txt)-$(sha256sum "$0" | cut -c1-16)-$1.code"
	[ -f "$key" ] || { "$bin" "$roms" "$eeprom" "$key.$$" "$0:$1" 2> /dev/null && mv "$key.$$" "$key"; }' \
	< "$work/list"
python3 - "$work" > port/extract/code_68k.txt <<'EOF'
import glob, sys
executed = bytearray(0x400000)
for f in glob.glob(sys.argv[1] + '/*.code'):
    for l in open(f):
        a, b = (int(v, 16) for v in l.split())
        executed[a:b] = b'\1' * (b - a)
print('# start end(excluded): bytes of 68000 instructions executed by the reference on all scenarios')
print('# generated by tools/code_68k.sh, do not edit (docs/sans-rom.md, full data coverage section)')
a = None
for i, x in enumerate(bytes(executed) + b'\0'):
    if x and a is None:
        a = i
    elif not x and a is not None:
        print(f'{a:06x} {i:06x}')
        a = None
EOF
echo "port/extract/code_68k.txt: $(grep -vc '^#' port/extract/code_68k.txt) ranges"
