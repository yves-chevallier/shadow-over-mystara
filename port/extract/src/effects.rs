//! Tables of the EFFCT family: `data/effects.json` (`ddsom_data::effects`, docs/assets.md).
//!
//! The tables are declared in `ddsom_data::effects` (name, address, space, element size). They sit among the code of
//! their handlers: unless its declaration gives its end, a table runs up to the next declared table or the next
//! code executed by the original (`code_68k.txt`), whichever comes first, and at most `MAX` bytes.

use std::io;
use std::path::Path;

use ddsom_data::effects::{EffectTables, Spec, Table};
use ddsom_data::json;

use crate::rom::Program;

/// Starts of the 68000 code executed by the reference (`code_68k.txt`, generated by tools/code_68k.sh).
const CODE: &str = include_str!("../code_68k.txt");

/// Longest table read without an explicit end (bytes).
const MAX: u32 = 0x400;

fn code_starts() -> Vec<u32> {
    let mut starts: Vec<u32> = CODE
        .lines()
        .filter(|l| !l.starts_with('#') && !l.trim().is_empty())
        .map(|l| u32::from_str_radix(l.split_whitespace().next().unwrap(), 16).expect("code_68k.txt"))
        .collect();
    starts.sort();
    starts
}

/// End (excluded) of the table declared by `spec`: its own end, otherwise the next table or code, at most `MAX` bytes
/// further; rounded down to whole elements.
fn end_of(spec: &Spec, code: &[u32]) -> u32 {
    let end = spec.end.unwrap_or_else(|| {
        let next_table = EffectTables::SPECS.iter().map(|s| s.rom).filter(|&a| a > spec.rom).min();
        let next_code = code.iter().copied().find(|&a| a > spec.rom);
        [next_table, next_code, Some(spec.rom + MAX)].into_iter().flatten().min().unwrap()
    });
    let size = spec.size as u32;
    spec.rom + (end - spec.rom) / size * size
}

pub fn effects(rom: &Program) -> EffectTables {
    let code = code_starts();
    EffectTables::build(|spec| {
        let bytes: Vec<u8> = (spec.rom..end_of(spec, &code))
            .map(|a| if spec.program { rom.prog8(a) } else { rom.rd8(a) })
            .collect();
        Table::from_bytes(spec, &bytes)
    })
}

pub fn extract(roms: &Path, path: &Path) -> io::Result<()> {
    let rom = Program::load(roms)?;
    std::fs::create_dir_all(path.parent().unwrap())?;
    json::save(path, &effects(&rom).to_map(), 2)
}
