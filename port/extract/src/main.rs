//! Extracts the Shadow over Mystara resources from the user's ROMs.
//!
//!     extract <roms_dir> <assets_dir> [gfx|palettes|sounds|sprites|levels|terrain|texts|music|data...]
//!
//! With no category, everything is extracted. All formats are lossless: the engine can recover
//! exactly the original data (`cargo test -p ddsom-assets`, see docs/assets.md).
//! The produced files derive from the ROMs: they stay local, never committed.

use extract::*;
use std::path::Path;

const CATEGORIES: [&str; 9] = ["gfx", "palettes", "sounds", "sprites", "levels", "terrain", "texts", "music", "data"];

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() < 3 || args[3..].iter().any(|c| !CATEGORIES.contains(&c.as_str())) {
        eprintln!("usage: extract <roms_dir> <assets_dir> [{}...]", CATEGORIES.join("|"));
        std::process::exit(2);
    }
    let (roms, out) = (Path::new(&args[1]), Path::new(&args[2]));
    let wanted = |c: &str| args.len() == 3 || args[3..].iter().any(|a| a == c);
    let run = || -> std::io::Result<()> {
        std::fs::create_dir_all(out)?;
        if wanted("gfx") {
            gfx::extract(roms, &out.join("gfx"))?;
        }
        if wanted("palettes") {
            palettes::extract(roms, &out.join("palettes.png"))?;
            scene_palettes::extract(roms, &out.join("scene_palettes.json"))?;
        }
        if wanted("sounds") {
            sounds::extract(roms, &out.join("sounds"))?;
        }
        if wanted("sprites") {
            sprites::extract(roms, &out.join("sprites"))?;
            tables::extract(roms, &out.join("sprites/tables.json"))?;
        }
        if wanted("levels") {
            levels::extract(roms, &out.join("levels.json"))?;
        }
        if wanted("terrain") {
            terrain::extract(roms, &out.join("terrain.json"))?;
        }
        if wanted("texts") {
            texts::extract(roms, &out.join("texts.json"))?;
        }
        if wanted("music") {
            music::extract(roms, &out.join("sound/music.json"))?;
            music::extract_dsp(roms, &out.join("sound/qsound_dsp.json"))?;
        }
        if wanted("data") {
            spawns::extract(roms, &out.join("data/spawns.json"))?;
            speeds::extract(roms, &out.join("data/speeds.json"))?;
            effects::extract(roms, &out.join("data/effects.json"))?;
            objects::extract(roms, &out.join("data/objects.json"))?;
            set::extract(roms, &out.join("data/set.json"))?;
            player_tables::extract(roms, &out.join("data/player_tables.json"))?;
            data::extract(roms, &out.join("data"))?;
        }
        if wanted("data") {
            // last: everything the other files do not describe, except 68000 code
            remainder::extract(roms, out)?;
        }
        std::fs::write(out.join("README.md"), README)?;
        Ok(())
    };
    if let Err(e) = run() {
        eprintln!("extraction failed: {e}");
        std::process::exit(1);
    }
}

const README: &str = "\
# Resources extracted from Shadow over Mystara

Generated by `extract` from the ROMs: do not commit.

## gfx/cells_NN.png

The whole graphics ROM, in 16x16-pixel cells in ROM order: cell `c` is in
`cells_{c / 4096}.png`, column `c % 64`, row `(c / 64) % 64`. 4-bit indexed PNG: the value is
the color index in the palette chosen by the game (15 = transparent).

The other tile shapes are different readings of the same bytes:
- 8x8 tile `t` (layer 1): half-cell, cell `0x10000 + t / 2`, rows `8 * (t % 2)..`,
  columns `8 * (map column % 2)..`;
- 32x32 tile `t` (layer 3): cells `0x10000 + 4 t ..`, row `y` of the tile is row
  `2 * (y % 8)` (left half) and `2 * (y % 8) + 1` (right half) of cell `y / 8`.

## palettes.png

The game's palette library (program ROM 0x253000): one 16-color palette per row.
Red, green, blue and brightness on 4 bits, stored multiplied by 17 in R, G, B and A.
Displayed color: `component * 0x11 * (0x0f + 2 * brightness) / 0x2d`.

## sounds/NNN.wav

The valid QSound samples (342 of the 345 entries of the sound driver table, Z80 ROM 0x49e8), 8-bit PCM at 24 038 Hz (the chip's
playback rate 1.0). The `smpl` chunk gives the loop and the reference note (60 = middle C).

## sprites/frames.json, sprites/anims.json

Sprite definitions: the 21 887 frames (cell assemblies, ROM table 0x293000) and the animation scripts
(sets and entries). JSON, ROM addresses in hexadecimal; format detailed in docs/assets.md.

## sprites/tables.json

Object tables tied to sprites: collision boxes, visibility boxes, ground marks, frame
lists read directly by the code.

## scene_palettes.json

Palettes loaded by each scene (numbers or addresses in the `palettes.png` library).

## levels.json

Scenery maps (scroll 2 and scroll 3): 2x2-cell blocks, 256x256-pixel strips and strip tables
of the 115 scenes; fixed scroll 1 frames (8x8 cells). Format detailed in docs/assets.md.

## terrain.json

Fixed terrain maps (scenes 2 and 0x14) and terrain type tables (collision with the scenery).

## sound/music.json

Music and effects of the sound driver, as indexed tables (`ddsom_sound::SoundData`): sounds, tracks
(instructions as tokens; a read position is `[track, byte]`), instrument banks, sample records and driver
tables (volumes, envelopes, pitches).

## sound/qsound_dsp.json

Tables of the QSound DSP program (`dl-1425.bin`) read by its emulation: pan, ADPCM step,
filter coefficients.

## data/rest.json

Tables read by the game in Rust that the other files do not cover: tile and palette scripts
of the SETs, player sub-objects (weapon and shield), aura palettes, task stacks, sound panning.

## data/natives.json, data/reste.json

The rest of the program region: `natives.json`, the measured zones that the native routines read;
`reste.json`, everything no other file describes, except the executed 68000 code (ranges listed in
`code`), as blocks of hexadecimal bytes. With them, the rebuilt program region equals the ROM outside code
(docs/sans-rom.md 'full data coverage').

## data/speeds.json

Speed tables of the objects (motion by table): (vx, vy) per index, and the two arrays of tables of the code.

## data/effects.json

Tables of the visual effects (EFFCT family), by name: address, space, element size, values.

## data/objects.json

Tables of the enemy shots, special objects, pickup objects and crates (ESHL, SOBJ, ITEM and BOX families), in the
same form as data/effects.json.

## data/player_tables.json

Tables of the players (common state machine, cinematics, reactions to hits, spells, shots and effects of the
players), in the same form as data/effects.json.

## data/spawns.json

Scene spawn scripts (enemies, scenery, objects that enter as the screen scrolls).

## data/players.json, combat.json, enemies.json, boxes.json, scenes.json, misc.json, dialogs.json

Game data tables (characters, hit reactions, enemies, crates, scenes, demonstrations)
and texts (credits, dialogs and balloons in the three languages): one table per entry, rows laid out
as in ROM; meaning of the tables and fields in docs/assets.md.

## texts.json

Texts of the character layer (descriptors of the text routines) and balloon names; control
codes explained in docs/assets.md.
";
